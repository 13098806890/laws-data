def build_xlsx_index() -> dict:
    index = {}
    for path in glob.glob(str(SRC_BASE / '**/*.xlsx'), recursive=True):
        try:
            import xlrd
            wb = xlrd.open_workbook(path)
        except Exception:
            continue
        for sheet in wb.sheets():
            for i in range(1, sheet.nrows):
                row = sheet.row_values(i)
                title = str(row[0]).strip()
                pub   = str(row[1]).strip()
                eff   = str(row[2]).strip()
                cat   = str(row[3]).strip()
                key   = f'{title}_{pub.replace("-", "")}'
                if key not in index:
                    index[key] = {'effective_date': eff, 'category': cat}
    return index


def build_domain_index() -> dict:
    idx = {}
    for dept in DEPT_DIRS:
        dept_path = LAWS_REPO / dept
        if not dept_path.is_dir():
            continue
        for fname in dept_path.iterdir():
            if fname.suffix != '.md' or fname.name.startswith('_'):
                continue
            raw = re.sub(r'\(\d{4}-\d{2}-\d{2}\)', '', fname.stem).strip()
            for variant in [raw, raw.replace('中华人民共和国', '').strip()]:
                idx[re.sub(r'\s+', '', variant)] = dept

    for title, dept in MANUAL_DOMAINS.items():
        for variant in [title, title.replace('中华人民共和国', '').strip()]:
            idx[re.sub(r'\s+', '', variant)] = dept

    return idx


def get_legal_domain(title: str, data: dict, domain_idx: dict):
    clean = lambda s: re.sub(r'\s+', '', s)

    # Layer 1: Exact/title match (MANUAL_DOMAINS + Laws repo directory structure)
    for key in [clean(title), clean(title.replace('中华人民共和国', ''))]:
        if key in domain_idx:
            return domain_idx[key]

    # False positive filter: '民法' in '人民法院' should not count
    def is_valid_kw(kw: str, text: str) -> bool:
        if kw == '民法' and ('人民法院' in text or '最高人民法院' in text):
            return False
        return True

    # Layer 2: Scoring — count keyword matches per domain, pick highest
    def score_keywords(text: str) -> list[tuple[str, int]]:
        scores = {}
        for dept, keywords in KEYWORD_RULES:
            s = sum(1 for kw in keywords if is_valid_kw(kw, text) and kw in text)
            if s > 0:
                scores[dept] = s
        # Strong signal bonus: if title contains a strong signal keyword,
        # add +10 to the corresponding domain
        if text == title:
            for signal, (domain, bonus) in STRONG_SIGNALS.items():
                if signal in title and domain in scores:
                    scores[domain] += bonus
                elif signal in title:
                    scores[domain] = bonus
        return sorted(scores.items(), key=lambda x: (-x[1], x[0]))

    ranked = score_keywords(title)

    # Title has no domain keywords: use category-based default
    if not ranked:
        if data.get('category') in ('行政法规', '部门规章'):
            return '行政法'
        if data.get('category') == '司法解释':
            return '诉讼与非诉讼程序法'
        return None

    if not ranked:
        if data.get('category') in ('行政法规', '部门规章'):
            return '行政法'
        return None

    # If there's a clear winner (unique top score), return it
    top_dept, top_score = ranked[0]
    if len(ranked) == 1 or ranked[1][1] < top_score:
        return top_dept

    # Tie: use domain priority (order in KEYWORD_RULES) as tiebreaker
    # Higher-priority domain comes first in the list
    domain_order = [d for d, _ in KEYWORD_RULES]
    tied = [d for d, s in ranked if s == top_score]
    tied.sort(key=lambda d: domain_order.index(d) if d in domain_order else 999)
    return tied[0]
